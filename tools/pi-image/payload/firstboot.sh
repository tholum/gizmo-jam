#!/bin/bash
# Gizmo Jam Pi image: first-boot setup. Run once, as root, by cloud-init runcmd:
#   bash /boot/firmware/gizmo/firstboot.sh
# and (network steps only) by gizmo-firstboot-net.service:
#   /usr/local/lib/gizmo/firstboot.sh --net
#
# Safe to re-run: every step checks its own state. Never aborts on a
# non-critical failure; each step's result is recorded in
# /var/lib/gizmo/steps/<step> and summarised in /var/lib/gizmo/firstboot.done.
# Log: /var/log/gizmo-firstboot.log
#
# Exit codes: 0 ok (non-critical steps may have failed, see the summary),
#             1 a critical step failed (config, helper install, Godot),
#             2 usage, 75 (--net only) network work must be retried later.
#
# Test hooks (used by payload/tests/chroot_test.sh, never set on a real Pi):
#   GIZMO_TEST_CHROOT=1  skip what needs a booted system: `tailscale up`,
#                        the reboot, and the "is the display manager running" probe
#   GIZMO_TEST_NO_NET=1  pretend the network is down
# Steps are called indirectly through step(); shellcheck 0.9 reports them as
# unreachable (SC2317), so that check is disabled for this file.
# shellcheck disable=SC2317
set -u
umask 022

PAYLOAD=${GIZMO_PAYLOAD:-/boot/firmware/gizmo}
BOOTFS=${PAYLOAD%/*}
STATE=/var/lib/gizmo
LOG=/var/log/gizmo-firstboot.log
LIBDIR=/usr/local/lib/gizmo
UNIT=gizmo-firstboot-net.service
TEST_CHROOT=${GIZMO_TEST_CHROOT:-}
TS_MAX_ATTEMPTS=5

usage() {
    cat <<'EOF'
Usage: firstboot.sh          full first-boot setup (cloud-init runcmd)
       firstboot.sh --net    only the network steps (gizmo-firstboot-net.service)
Log: /var/log/gizmo-firstboot.log   Summary: /var/lib/gizmo/firstboot.done
EOF
}

MODE=full
case "${1:-}" in
    "") ;;
    --net) MODE=net ;;
    -h|--help) usage; exit 0 ;;
    *) usage >&2; exit 2 ;;
esac

if [ "$(id -u)" != 0 ]; then
    echo "firstboot.sh: must run as root" >&2
    exit 1
fi

mkdir -p "$STATE/steps"
touch "$LOG"
chmod 0640 "$LOG"
chgrp adm "$LOG" 2>/dev/null || true
exec > >(tee -a "$LOG") 2>&1

log() { printf '%s [gizmo-firstboot] %s\n' "$(date -Is)" "$*"; }

shred_file() {
    [ -e "$1" ] || return 0
    shred -u -z -n 3 "$1" 2>/dev/null || rm -f "$1"
    if [ -e "$1" ]; then log "ERROR: could not remove $1"; return 1; fi
    log "shredded $1"
}

# Whatever happens, the Tailscale key must not stay on the world-readable FAT
# partition.
trap 'shred_file "$PAYLOAD/secrets/tailscale.key" >/dev/null; rmdir "$PAYLOAD/secrets" 2>/dev/null' EXIT

declare -A RESULT=()
ORDER=()
CRITICAL_FAILED=0
NEED_REBOOT=0
REBOOT_REASON=""

# step NAME [critical] FUNCTION: 0 ok, 10 skipped (already done / not wanted),
# 20 deferred (needs network), anything else failed.
step() {
    local name=$1 critical=0 rc status
    shift
    if [ "$1" = critical ]; then critical=1; shift; fi
    log "--- step $name: start"
    "$@"
    rc=$?
    case $rc in
        0) status=ok ;;
        10) status=skipped ;;
        20) status=deferred ;;
        *) status="failed(rc=$rc)"; [ $critical = 1 ] && CRITICAL_FAILED=1 ;;
    esac
    RESULT[$name]=$status
    ORDER+=("$name")
    printf '%s %s\n' "$status" "$(date -Is)" >"$STATE/steps/$name"
    log "--- step $name: $status"
    return 0
}

# ---------------------------------------------------------------------------
GIZMO_USER=""
GIZMO_HOSTNAME=""
GIZMO_GODOT_ZIP=""
GIZMO_GODOT_SHA512=""
GIZMO_TAILSCALE=""
GIZMO_TAILSCALE_HOSTNAME=""
GIZMO_TAILSCALE_SSH=""
GIZMO_EXTRA_PACKAGES=""
GIZMO_KIOSK=""
GIZMO_BUILD_ID=""
UHOME=""
UGROUP=""

load_env() {
    local envf="$PAYLOAD/firstboot.env"
    if [ "$MODE" = net ] || [ ! -f "$envf" ]; then
        [ -f "$STATE/firstboot.env" ] && envf="$STATE/firstboot.env"
    fi
    if [ ! -f "$envf" ]; then
        log "ERROR: no firstboot.env in $PAYLOAD or $STATE"
        return 1
    fi
    # shellcheck disable=SC1090  # generated by build.py
    . "$envf" || { log "ERROR: cannot source $envf"; return 1; }
    log "config: $envf (build ${GIZMO_BUILD_ID:-?})"
    if ! [[ "$GIZMO_USER" =~ ^[a-z_][a-z0-9_-]*$ ]]; then
        log "ERROR: bad GIZMO_USER '$GIZMO_USER'"
        return 1
    fi
    if ! getent passwd "$GIZMO_USER" >/dev/null; then
        log "ERROR: user $GIZMO_USER does not exist (did cloud-init create it? see /var/log/cloud-init.log)"
        return 1
    fi
    UHOME=$(getent passwd "$GIZMO_USER" | cut -d: -f6)
    UGROUP=$(id -gn "$GIZMO_USER")
    if [ "$envf" != "$STATE/firstboot.env" ]; then
        install -m 0644 "$envf" "$STATE/firstboot.env" || return 1
    fi
    mkdir -p /etc/gizmo
    printf '# written by gizmo firstboot.sh\nGIZMO_USER="%s"\nGIZMO_BUILD_ID="%s"\n' \
        "$GIZMO_USER" "$GIZMO_BUILD_ID" >/etc/gizmo/gizmo.conf
    return 0
}

# Move the Tailscale key off the FAT partition (root-only copy on the rootfs,
# kept only until `tailscale up` has used it) and shred the original.
secure_secrets() {
    local src="$PAYLOAD/secrets/tailscale.key" dst="$STATE/secrets/tailscale.key" rc=0
    if [ ! -f "$src" ]; then
        if [ "$GIZMO_TAILSCALE" = 1 ] && [ ! -f "$dst" ] && [ ! -f "$STATE/tailscale.done" ]; then
            log "WARNING: GIZMO_TAILSCALE=1 but $src is missing"
            return 1
        fi
        return 10
    fi
    if [ "$GIZMO_TAILSCALE" = 1 ] && [ ! -f "$STATE/tailscale.done" ]; then
        install -d -m 0700 "$STATE/secrets" && install -m 0600 "$src" "$dst" || rc=1
        [ $rc = 0 ] && log "Tailscale key moved to $dst (root only, shredded after use)"
    else
        log "Tailscale key present but not needed; discarding it"
    fi
    shred_file "$src" || rc=1
    rmdir "$PAYLOAD/secrets" 2>/dev/null
    return "$rc"
}

install_payload() {
    local f rc=0
    install -d -m 0755 /usr/local/bin "$LIBDIR" || return 1
    for f in "$PAYLOAD"/bin/*; do
        [ -f "$f" ] || continue
        install -m 0755 "$f" /usr/local/bin/ || rc=1
        log "installed /usr/local/bin/${f##*/}"
    done
    if [ "$(readlink -f "$0")" != "$(readlink -f "$LIBDIR/firstboot.sh")" ]; then
        install -m 0755 "$0" "$LIBDIR/firstboot.sh" || rc=1
    fi
    install -m 0644 "$PAYLOAD/systemd/$UNIT" "/etc/systemd/system/$UNIT" || rc=1
    systemctl daemon-reload 2>/dev/null || true
    return "$rc"
}

setup_sudo() {
    local f=/etc/sudoers.d/010_gizmo-nopasswd tmp
    tmp=$(mktemp) || return 1
    printf '# written by gizmo firstboot.sh\n%s ALL=(ALL) NOPASSWD:ALL\n' "$GIZMO_USER" >"$tmp"
    if cmp -s "$tmp" "$f"; then rm -f "$tmp"; return 10; fi
    if ! visudo -cqf "$tmp"; then
        log "ERROR: generated sudoers file does not validate"
        rm -f "$tmp"
        return 1
    fi
    install -m 0440 -o root -g root "$tmp" "$f"
    local rc=$?
    rm -f "$tmp"
    return "$rc"
}

install_godot() {
    local zip="$PAYLOAD/$GIZMO_GODOT_ZIP" want have tmp bin name
    want=$(printf '%s' "$GIZMO_GODOT_SHA512" | tr 'A-F' 'a-f')
    if [ -z "$want" ]; then
        log "ERROR: GIZMO_GODOT_SHA512 is empty; refusing to install an unverified Godot"
        return 1
    fi
    if [ -x /opt/godot/godot ] && [ "$(cat /opt/godot/.zip-sha512 2>/dev/null)" = "$want" ]; then
        log "Godot already installed: $(readlink /opt/godot/godot)"
        ln -sfn /opt/godot/godot /usr/local/bin/godot
        return 10
    fi
    if [ -z "$GIZMO_GODOT_ZIP" ] || [ ! -f "$zip" ]; then
        log "ERROR: Godot zip not found: $zip"
        return 1
    fi
    log "verifying $zip"
    have=$(sha512sum "$zip" | cut -d' ' -f1)
    if [ "$have" != "$want" ]; then
        log "ERROR: sha512 mismatch for $zip: got $have"
        return 1
    fi
    install -d -m 0755 /opt/godot || return 1
    tmp=$(mktemp -d /opt/godot/.unzip.XXXXXX) || return 1
    if ! unzip -q -o "$zip" -d "$tmp"; then
        log "ERROR: unzip failed"
        rm -rf "$tmp"
        return 1
    fi
    bin=$(find "$tmp" -maxdepth 2 -type f -name 'Godot_v*' ! -name '*.zip' | head -n 1)
    if [ -z "$bin" ]; then
        log "ERROR: no Godot_v* binary inside $zip"
        rm -rf "$tmp"
        return 1
    fi
    name=${bin##*/}
    install -m 0755 "$bin" "/opt/godot/$name" || { rm -rf "$tmp"; return 1; }
    rm -rf "$tmp"
    ln -sfn "$name" /opt/godot/godot
    ln -sfn /opt/godot/godot /usr/local/bin/godot
    printf '%s\n' "$want" >/opt/godot/.zip-sha512
    log "installed /opt/godot/$name (/opt/godot/godot, /usr/local/bin/godot)"
    return 0
}

setup_user() {
    local d g rc=0
    for d in "$UHOME/gizmo" "$UHOME/gizmo/logs" "$UHOME/gizmo/shots"; do
        install -d -o "$GIZMO_USER" -g "$UGROUP" -m 0755 "$d" || rc=1
    done
    # vcgencmd needs video; the GPU render node needs render.
    for g in video render input; do
        getent group "$g" >/dev/null || continue
        if ! id -nG "$GIZMO_USER" | tr ' ' '\n' | grep -qx "$g"; then
            usermod -aG "$g" "$GIZMO_USER" && log "added $GIZMO_USER to group $g" || rc=1
        fi
    done
    return "$rc"
}

autologin_user() {
    sed -n 's/^autologin-user=//p' /etc/lightdm/lightdm.conf 2>/dev/null | tail -n 1
}

display_manager_active() {
    [ -z "$TEST_CHROOT" ] && systemctl is-active --quiet display-manager.service
}

# Desktop autologin (cloud-init's userconf/cancel-rename normally already did
# this before LightDM started; this is belt and braces) and no screen blanking.
setup_desktop() {
    local before after rc=0
    before=$(autologin_user)
    SUDO_USER="$GIZMO_USER" raspi-config nonint do_boot_behaviour B4 || rc=1
    after=$(autologin_user)
    if [ "$after" != "$GIZMO_USER" ]; then
        log "ERROR: lightdm autologin-user is '$after' after do_boot_behaviour B4"
        rc=1
    elif [ "$before" != "$after" ]; then
        log "autologin-user changed: '$before' -> '$after'"
        if display_manager_active; then
            NEED_REBOOT=1
            REBOOT_REASON="LightDM was already running with autologin-user='$before'"
        fi
    else
        log "autologin-user already $after"
    fi
    SUDO_USER="$GIZMO_USER" raspi-config nonint do_blanking 1 || { log "do_blanking 1 failed"; rc=1; }
    return "$rc"
}

# The Wi-Fi password is in /boot/firmware/network-config (world-readable FAT).
# cloud-init renders it once per instance-id to /etc/netplan/50-cloud-init.yaml
# (root only). NoCloud's default update events are BOOT_NEW_INSTANCE only and
# build.py emits no `updates:` key, so later boots never re-read it: once the
# rendered file has the Wi-Fi config, the bootfs copy can go.
scrub_wifi() {
    local nc="$BOOTFS/network-config" np=/etc/netplan/50-cloud-init.yaml
    [ -f "$nc" ] || return 10
    grep -qE '^[[:space:]]*(wifis|password)[[:space:]]*:' "$nc" || return 10
    if [ ! -s "$np" ] || ! grep -q 'wifis' "$np"; then
        log "WARNING: $np has no Wi-Fi config yet; leaving $nc untouched"
        return 1
    fi
    cat >"$nc.tmp" <<EOF || return 1
# Wi-Fi settings from this file were applied on first boot and removed by
# gizmo firstboot.sh so the password does not sit on the FAT partition.
# The live copy is /etc/netplan/50-cloud-init.yaml (root only).
# To change Wi-Fi on the Pi: sudo nmtui  (or edit that file + sudo netplan apply)
EOF
    mv -f "$nc.tmp" "$nc" || return 1
    sync
    log "removed the Wi-Fi password from $nc"
    return 0
}

# --------------------------------------------------------------- network
net_ok() {
    [ -n "${GIZMO_TEST_NO_NET:-}" ] && return 1
    # plain HTTP: works before the clock is synced
    curl -fsS -o /dev/null --max-time 15 http://deb.debian.org/debian/dists/trixie/Release ||
        curl -fsS -o /dev/null --max-time 15 http://archive.raspberrypi.com/debian/dists/trixie/Release
}

wait_net() {
    local limit=$1 start
    start=$(date +%s)
    until net_ok >/dev/null 2>&1; do
        [ $(( $(date +%s) - start )) -ge "$limit" ] && return 1
        sleep 5
    done
}

# The Pi has no RTC; HTTPS (Tailscale repo) fails if the clock is far behind.
wait_time_sync() {
    local i=0 v
    while [ $i -lt 60 ]; do
        v=$(timedatectl show -p NTPSynchronized --value 2>/dev/null) || return 0
        [ "$v" = yes ] && return 0
        sleep 2
        i=$((i + 2))
    done
    log "WARNING: clock not NTP-synchronised after 60s; continuing"
}

APT_OPTS=(-y -q -o DPkg::Lock::Timeout=600 -o Acquire::Check-Date=false
          -o Dpkg::Options::=--force-confdef -o Dpkg::Options::=--force-confold)

apt_get() { DEBIAN_FRONTEND=noninteractive apt-get "${APT_OPTS[@]}" "$@"; }

# 0 = finished (some packages may have failed permanently), 1 = retry later
install_packages() {
    local pkgs p failed=()
    read -r -a pkgs <<<"$GIZMO_EXTRA_PACKAGES"
    [ ${#pkgs[@]} -gt 0 ] || return 0
    apt_get update || { log "apt-get update failed"; return 1; }
    if apt_get install "${pkgs[@]}"; then
        printf 'ok %s\n' "${pkgs[*]}" >"$STATE/packages.done"
        return 0
    fi
    log "installing all of '${pkgs[*]}' failed; trying one by one"
    for p in "${pkgs[@]}"; do
        apt_get install "$p" || failed+=("$p")
    done
    if [ ${#failed[@]} -gt 0 ]; then
        log "WARNING: packages that could not be installed: ${failed[*]}"
        printf 'failed %s\n' "${failed[*]}" >"$STATE/packages.done"
    else
        printf 'ok %s\n' "${pkgs[*]}" >"$STATE/packages.done"
    fi
    return 0
}

ts_give_up_or_retry() {   # $1 = reason
    local n
    n=$(( $(cat "$STATE/tailscale.attempts" 2>/dev/null || echo 0) + 1 ))
    echo "$n" >"$STATE/tailscale.attempts"
    if [ "$n" -ge $TS_MAX_ATTEMPTS ]; then
        log "ERROR: Tailscale: $1; giving up after $n attempts"
        printf 'failed %s\n' "$1" >"$STATE/tailscale.done"
        shred_file "$STATE/secrets/tailscale.key"
        return 0
    fi
    log "Tailscale: $1 (attempt $n of $TS_MAX_ATTEMPTS); will retry"
    return 1
}

# 0 = finished (ok or given up; key shredded either way), 1 = retry later
setup_tailscale() {
    local key="$STATE/secrets/tailscale.key" codename host args
    if [ ! -f "$key" ]; then
        log "ERROR: Tailscale requested but no key at $key"
        printf 'failed no auth key\n' >"$STATE/tailscale.done"
        return 0
    fi
    if ! command -v tailscale >/dev/null 2>&1; then
        # shellcheck disable=SC1091  # present on every Debian system
        codename=$(. /etc/os-release && echo "${VERSION_CODENAME:-trixie}")
        log "installing Tailscale from pkgs.tailscale.com (debian $codename)"
        if ! curl -fsSL --max-time 60 "https://pkgs.tailscale.com/stable/debian/$codename.noarmor.gpg" \
                -o /usr/share/keyrings/tailscale-archive-keyring.gpg ||
           ! curl -fsSL --max-time 60 "https://pkgs.tailscale.com/stable/debian/$codename.tailscale-keyring.list" \
                -o /etc/apt/sources.list.d/tailscale.list ||
           ! apt_get update || ! apt_get install tailscale; then
            ts_give_up_or_retry "install failed"
            return $?
        fi
    fi
    # separately: `enable --now` is refused outright when systemd is not running
    systemctl enable tailscaled || log "WARNING: could not enable tailscaled"
    systemctl start tailscaled || log "WARNING: could not start tailscaled"
    host=${GIZMO_TAILSCALE_HOSTNAME:-${GIZMO_HOSTNAME:-$(hostname)}}
    args=(up "--auth-key=file:$key" "--hostname=$host" --timeout=120s)
    [ "$GIZMO_TAILSCALE_SSH" = 1 ] && args+=(--ssh)
    if [ -n "$TEST_CHROOT" ]; then
        log "TEST_CHROOT: not running: tailscale ${args[*]}"
    elif ! tailscale "${args[@]}"; then
        ts_give_up_or_retry "tailscale up failed"
        return $?
    fi
    log "Tailscale is up as $host"
    printf 'ok %s\n' "$host" >"$STATE/tailscale.done"
    shred_file "$key"
    return 0
}

# 0 = all network work finished, 10 = nothing to do, 20 = retry later
net_steps() {
    local retry=0
    exec 9>"$STATE/net.lock"
    flock -w 900 9 || { log "another network step is running"; return 20; }
    if [ -f "$STATE/net.done" ]; then
        log "network steps already finished"
        return 10
    fi
    local want_pkgs=0 want_ts=0
    [ -n "$GIZMO_EXTRA_PACKAGES" ] && [ ! -f "$STATE/packages.done" ] && want_pkgs=1
    [ "$GIZMO_TAILSCALE" = 1 ] && [ ! -f "$STATE/tailscale.done" ] && want_ts=1
    if [ $want_pkgs = 0 ] && [ $want_ts = 0 ]; then
        date -Is >"$STATE/net.done"
        return 10
    fi
    if ! wait_net 60; then
        log "no network (tried for 60s)"
        return 20
    fi
    wait_time_sync
    if [ $want_pkgs = 1 ]; then install_packages || retry=1; fi
    if [ $want_ts = 1 ]; then setup_tailscale || retry=1; fi
    [ $retry = 1 ] && return 20
    {
        date -Is
        [ -f "$STATE/packages.done" ] && printf 'packages=%s\n' "$(cat "$STATE/packages.done")"
        [ -f "$STATE/tailscale.done" ] && printf 'tailscale=%s\n' "$(cat "$STATE/tailscale.done")"
    } >"$STATE/net.done"
    return 0
}

network_step() {
    local rc
    net_steps
    rc=$?
    if [ "$rc" = 20 ]; then
        log "network steps deferred to $UNIT (retries every 2 minutes, also on later boots)"
        systemctl enable "$UNIT" 2>&1 || return 1
        if [ "$NEED_REBOOT" = 0 ]; then
            systemctl start --no-block "$UNIT" 2>&1 || true
        fi
    elif systemctl is-enabled --quiet "$UNIT" 2>/dev/null; then
        systemctl disable "$UNIT" 2>&1 || true
    fi
    return "$rc"
}

setup_kiosk() {
    [ "$GIZMO_KIOSK" = 1 ] || return 10
    /usr/local/bin/gizmo-kiosk on || return 1
    # cloud-final runs after the desktop has logged in, so the autostart entry
    # only takes effect next login: start the loop in the live session too.
    if [ "$NEED_REBOOT" = 0 ] && /usr/local/bin/gizmo-env --for "$GIZMO_USER" >/dev/null 2>&1; then
        /usr/local/bin/gizmo-kiosk start || true
    fi
    return 0
}

write_summary() {
    local n net=pending
    [ -f "$STATE/net.done" ] && net="done"
    {
        printf 'build_id=%s\n' "$GIZMO_BUILD_ID"
        printf 'completed=%s\n' "$(date -Is)"
        printf 'user=%s\n' "$GIZMO_USER"
        for n in "${ORDER[@]}"; do printf 'step.%s=%s\n' "$n" "${RESULT[$n]}"; done
        printf 'network=%s\n' "$net"
        [ -f "$STATE/packages.done" ] && printf 'packages=%s\n' "$(cat "$STATE/packages.done")"
        [ -f "$STATE/tailscale.done" ] && printf 'tailscale=%s\n' "$(cat "$STATE/tailscale.done")"
        printf 'godot=%s\n' "$(readlink /opt/godot/godot 2>/dev/null || echo missing)"
        printf 'critical_failure=%s\n' "$CRITICAL_FAILED"
        printf 'reboot=%s\n' "$( [ $NEED_REBOOT = 1 ] && echo "yes ($REBOOT_REASON)" || echo no)"
    } >"$STATE/firstboot.done.tmp"
    mv -f "$STATE/firstboot.done.tmp" "$STATE/firstboot.done"
    chmod 0644 "$STATE/firstboot.done"
    log "summary ($STATE/firstboot.done):"
    sed 's/^/    /' "$STATE/firstboot.done"
}

# ---------------------------------------------------------------------------
if [ "$MODE" = net ]; then
    log "=== network steps (from $UNIT)"
    if ! load_env; then
        exit 75
    fi
    net_steps
    rc=$?
    if [ "$rc" = 20 ]; then
        log "=== network steps will be retried"
        exit 75
    fi
    systemctl disable "$UNIT" 2>&1 || true
    if [ -f "$STATE/firstboot.done" ]; then
        sed -i 's/^network=.*/network=done/' "$STATE/firstboot.done"
        for f in packages tailscale; do
            if [ -f "$STATE/$f.done" ] && ! grep -q "^$f=" "$STATE/firstboot.done"; then
                printf '%s=%s\n' "$f" "$(cat "$STATE/$f.done")" >>"$STATE/firstboot.done"
            fi
        done
    fi
    log "=== network steps finished"
    exit 0
fi

log "=== Gizmo Jam first boot (payload $PAYLOAD)"
step config critical load_env
if [ "${RESULT[config]}" != ok ]; then
    CRITICAL_FAILED=1
    secure_secrets >/dev/null 2>&1
    write_summary
    exit 1
fi
step secrets secure_secrets
step helpers critical install_payload
step sudo setup_sudo
step godot critical install_godot
step userdirs setup_user
step desktop setup_desktop
step wifi_scrub scrub_wifi
step network network_step
step kiosk setup_kiosk
write_summary

if [ $NEED_REBOOT = 1 ]; then
    if [ -f "$STATE/firstboot.rebooted" ]; then
        log "a reboot would be needed ($REBOOT_REASON) but one was already done; not rebooting again"
    elif [ -n "$TEST_CHROOT" ]; then
        log "TEST_CHROOT: would reboot now ($REBOOT_REASON)"
    else
        date -Is >"$STATE/firstboot.rebooted"
        log "rebooting in 1 minute: $REBOOT_REASON"
        shutdown -r +1 "gizmo firstboot: reboot to apply desktop autologin" ||
            systemctl reboot --no-block
    fi
fi

log "=== first boot finished (critical_failure=$CRITICAL_FAILED)"
[ $CRITICAL_FAILED = 0 ] && exit 0
exit 1
